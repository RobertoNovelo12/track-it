const { test } = require('node:test');
const assert = require('node:assert/strict');
const crearEstado = require('./inventario-helper.cjs');
test('conserva selección entre páginas y bloquea bajas ya realizadas', () => {
    const warnings = [];
    const window = { location: { origin: 'https://track-it.test' }, trackitToast: (...args) => warnings.push(args) };
    const state = crearEstado(window);
    state.alternarPagina([1, 2], true, [2]);
    state.alternarPagina([3], true);
    assert.deepEqual(state.seleccion, ['1', '2', '3']);
    state.darDeBajaSeleccion('conjunta');
    assert.equal(warnings.length, 1);
    assert.equal(window.location.href, undefined);
    state.alternarSeleccion(2, false);
    state.darDeBajaSeleccion();
    assert.equal(state.menuSeleccion, 'baja');
    state.darDeBajaSeleccion('conjunta');
    const destino = new URL(window.location.href);
    assert.equal(destino.searchParams.get('equipos'), '1,3');
    assert.equal(destino.searchParams.get('modo'), 'conjunta');
    state.limpiarSeleccion();
    assert.deepEqual(state.seleccion, []);
    assert.deepEqual(state.seleccionBajas, []);
});
test('impide dar de baja más de diez equipos', () => {
    const warnings = [];
    const window = { location: {}, trackitToast: (...args) => warnings.push(args) };
    const state = crearEstado(window);
    state.alternarPagina(Array.from({ length: 11 }, (_, i) => i + 1), true);
    state.darDeBajaSeleccion('conjunta');
    assert.equal(warnings.length, 1);
    assert.equal(window.location.href, undefined);
});
